// Bundles src/shaders/phosphene.glsl against the shader-art-coding library,
// compile-checks it, and writes src/shaders/phosphene.frag.ts.
// Chapter boundaries come from src/timeline.json so the shader and the HUD
// share one timeline.
import {execFileSync} from 'node:child_process';
import {mkdtempSync, readFileSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';

const root = resolve(import.meta.dirname, '..');
const tools = resolve(root, '../.claude/skills/shader-art-coding/scripts/glsl_tools.py');
const timeline = JSON.parse(readFileSync(join(root, 'src/timeline.json'), 'utf8'));

const header = timeline.chapters
  .map((c) => `const float T_${c.id} = ${c.start.toFixed(3)};`)
  .concat(`const float T_END = ${timeline.durationInSeconds.toFixed(3)};`)
  .join('\n');

const source = readFileSync(join(root, 'src/shaders/phosphene.glsl'), 'utf8');
const dir = mkdtempSync(join(tmpdir(), 'phosphene-'));
const input = join(dir, 'phosphene.glsl');
const output = join(dir, 'phosphene.bundled.glsl');
writeFileSync(input, `${header}\n\n${source}`);

const run = (...args) => execFileSync('python3', ['-I', tools, ...args], {stdio: 'inherit'});
run('bundle', input, '-o', output);
run('check', output);

const glsl = readFileSync(output, 'utf8');
writeFileSync(
  join(root, 'src/shaders/phosphene.frag.ts'),
  `// Generated by scripts/build-shader.mjs from phosphene.glsl. Do not edit.\nexport const phospheneShadertoy = ${JSON.stringify(glsl)};\n`,
);
console.log('Wrote src/shaders/phosphene.frag.ts');
